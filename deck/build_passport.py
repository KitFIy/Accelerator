"""Обновление паспорта проекта: правит текст в исходном файле, оформление не трогает.

Запуск:  python deck/build_passport.py
Результат: deliverables/Axisec_passport.docx
Состав команды, контакты и название проекта остаются как в исходном паспорте.
"""

from __future__ import annotations

import copy
from pathlib import Path

from docx import Document

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "source" / "passport_original.docx"
OUT = ROOT / "deliverables" / "Axisec_passport.docx"


def set_tail(paragraph, text: str, keep: int = 1):
    """Оставляет первые keep фрагментов (подпись), остальной текст заменяет одним фрагментом."""
    runs = paragraph.runs
    runs[keep].text = text
    for r in runs[keep + 1:]:
        r._r.getparent().remove(r._r)


def set_all(paragraph, text: str):
    runs = paragraph.runs
    runs[0].text = text
    for r in runs[1:]:
        r._r.getparent().remove(r._r)


def add_labeled(paragraph, label: str, text: str, bold_src, plain_src):
    """Добавляет в пустой абзац «подпись: текст» с оформлением соседних абзацев."""
    for src, value in ((bold_src, label), (plain_src, text)):
        run = paragraph.add_run(value)
        if src._r.rPr is not None:
            if run._r.rPr is not None:
                run._r.remove(run._r.rPr)
            run._r.insert(0, copy.deepcopy(src._r.rPr))


